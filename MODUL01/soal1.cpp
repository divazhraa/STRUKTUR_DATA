#include<iostream>
using namespace std;
int main(){
    float a, b, tambah, kurang, kali, bagi; 
    cin>>a;
    cin>>b;
    tambah = a + b;
    kurang= a-b;
    kali= a*b;
    bagi=a/b;
    cout<<"Hasil penjumlahan: "<<tambah<<endl;
    cout<<"Hasil pengurangan: "<<kurang<<endl;
    cout<<"Hasil pengurangan: "<<kali<<endl;
    cout<<"Hasil pembagian: "<<bagi;
    return 0;
}